-- ============================================================
-- Свободные слоты: на 7 дней вперёд, по 3 в день у каждого мастера
-- (10:00, 13:00, 16:00; со слотами записей выше не пересекаются)
-- ============================================================

INSERT INTO time_slot (id, master_id, start_time, end_time)
SELECT
    ('71000000-0000-0000-0000-'
        || lpad((row_number() OVER (ORDER BY m.id, d.n, h.hour))::text, 12, '0'))::uuid,
    m.id,
    CURRENT_DATE + d.n * INTERVAL '1 day' + h.hour,
    CURRENT_DATE + d.n * INTERVAL '1 day' + h.hour + INTERVAL '1 hour'
FROM (VALUES
        ('10000000-0000-0000-0000-000000000002'::uuid),
        ('10000000-0000-0000-0000-000000000003'::uuid)
     ) AS m(id)
CROSS JOIN generate_series(1, 7) AS d(n)
CROSS JOIN (VALUES
        (INTERVAL '10 hours'),
        (INTERVAL '13 hours'),
        (INTERVAL '16 hours')
     ) AS h(hour);


