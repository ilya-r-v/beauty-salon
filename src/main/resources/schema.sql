CREATE EXTENSION IF NOT EXISTS pgcrypto;

DROP TABLE IF EXISTS review CASCADE;
DROP TABLE IF EXISTS booking CASCADE;
DROP TABLE IF EXISTS service_variant CASCADE;
DROP TABLE IF EXISTS service CASCADE;
DROP TABLE IF EXISTS service_type CASCADE;
DROP TABLE IF EXISTS master_profile CASCADE;
DROP TABLE IF EXISTS client CASCADE;
DROP TABLE IF EXISTS role CASCADE;

CREATE TABLE role (
    id   UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    name VARCHAR(50) NOT NULL UNIQUE
);

CREATE TABLE client (
    id            UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    name          VARCHAR(100) NOT NULL,
    phone         VARCHAR(20)  NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role_id       UUID NOT NULL REFERENCES role(id)
);

CREATE TABLE master_profile (
    client_id   UUID PRIMARY KEY REFERENCES client(id) ON DELETE CASCADE,
    avatar_url  VARCHAR(255),
    description TEXT,
    rating      REAL NOT NULL DEFAULT 0 CHECK (rating >= 0 AND rating <= 5)
);

CREATE TABLE service_type (
    id   UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    name VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE service (
    id              UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    title           VARCHAR(150) NOT NULL,
    master_id       UUID NOT NULL REFERENCES master_profile(client_id) ON DELETE CASCADE,
    service_type_id UUID NOT NULL REFERENCES service_type(id)
);

CREATE TABLE service_variant (
    id          UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    title       VARCHAR(150) NOT NULL,
    description TEXT,
    price       NUMERIC(10,2) NOT NULL CHECK (price > 0),
    service_id  UUID NOT NULL REFERENCES service(id) ON DELETE CASCADE
);

CREATE TABLE booking (
    id                  UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    service_variant_id  UUID NOT NULL REFERENCES service_variant(id),
    status              VARCHAR(20) NOT NULL DEFAULT 'PENDING'
                         CHECK (status IN ('PENDING','CONFIRMED','COMPLETED','CANCELLED')),
    master_id           UUID NOT NULL REFERENCES master_profile(client_id),
    booking_time        TIMESTAMP NOT NULL,
    client_id           UUID NOT NULL REFERENCES client(id)
);

CREATE TABLE review (
    id        UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    author_id UUID NOT NULL REFERENCES client(id),
    master_id UUID NOT NULL REFERENCES master_profile(client_id),
    content   TEXT NOT NULL
);


